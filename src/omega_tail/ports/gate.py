"""Pare-feu Funnel : ce que l'application demande a la machine (HAProxy, certificat, essais de bout en bout)."""
from __future__ import annotations

from typing import Protocol


class GateAdmin(Protocol):
    """Interface d'administration d'HAProxy (socket local, droits 600)."""
    def command(self, line: str) -> str: ...
    def master(self, line: str) -> str: ...


class GateMachine(Protocol):
    def haproxy(self) -> str:
        """Chemin d'HAProxy ; vide s'il n'est pas installe."""
        ...
    def check_config(self, path: str) -> tuple[bool, str]: ...
    def fetch_certificate(self, dns_name: str, cert: str, key: str) -> tuple[bool, str]: ...
    def certificate_expiry_days(self, pem: str) -> int | None: ...
    def local_probe(self, gate_port: int, dns_name: str) -> tuple[bool, str]: ...
    def public_probe(self, dns_name: str, port: int) -> tuple[bool, str]: ...
    def set_cron(self, marker: str, line: str) -> tuple[bool, str]:
        """Pose (ou retire si `line` est vide) la ligne marquee dans la crontab de l'utilisateur."""
        ...
    def install_command(self) -> tuple[str, ...]:
        """Installation d'HAProxy par le gestionnaire de paquets (vide : inconnu)."""
        ...
